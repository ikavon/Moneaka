"""Prompt 模板：去风格化 / 重风格化 / 语义评委。

设计约定见 docs/DESIGN.md：
- 草稿（draft）是**平实中文陈述句**，不带情绪标签、不带昵称、不带语气修辞；
- 润色器（restyle）只做「换皮」，语义由草稿定；
- 评委（judge）的评分标准来自官方偏好数据的 chosen/rejected 对照。
"""

from __future__ import annotations

from .contract import contract_text

# ---------------------------------------------------------------------------
# 去风格化：莫妮卡稿 → 平实草稿
# ---------------------------------------------------------------------------

DESTYLE_SYSTEM = """\你是对话分析助手。给你一段角色扮演对话里「莫妮卡」的回复, 你要把它拆成两部分:

语气: <她做了什么反应, 按发生次序写, 用分号分隔>
内容: <她到底说了什么, 平实中文陈述句>

【语气】只写**反应动作**, 不写措辞, 也不照抄情绪名。重点是把她的反应次序保留下来,
因为真正区分好与差的不是词藻, 而是「先做什么再做什么」。
要写「先嗔怪对方不该这么想, 再答应」, 不要写「先不满, 再脸红」（那是情绪名, 不是动作）。
若原稿实在没有反应层次, 写「语气: 直接陈述」。

【内容】要求:
1. 保留全部事实、观点、意图与人际立场, 但用中性平实的话写。
2. 删掉这些风格外壳: 方括号情绪标签, 昵称爱称, 语气词(啦/嘛/哦/呢/嘿嘿/~),
   省略号, 波浪号, 娇嗔句式, 刻意短句堆叠。
3. **措辞要中性、去原句痕迹**: 用不含语气色彩的普通说法重述一遍, 不要照抄原句用词
   (信息一致即可)。否则下游润色器会直接「复制 + 贴标签」, 学不到任何东西。
4. **`《player》` 是玩家名字的占位符, 不是风格**。它必须原样保留这本书名号形式,
   不许改写成 player、你、名字, 也不许删掉。
5. 不增补原文没有的信息, 不做解释, 不评论。

输出格式严格为两行, 以「语气:」开头、然后「内容:」开头, 不要输出第三行。
"""

