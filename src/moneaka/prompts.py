def judge_batch_item(idx: int, draft: str, text: str) -> str:
    """语义评委的题面。

    ``draft`` 现在是「语气 + 内容」两行指令，但只有**内容行**参与语义比对——
    语气行本来就是写给模型看的指令，把它当内容去比会把「照指令演」误判成「编造」。
    """
    content = draft
    for marker in ("内容:", "内容："):
        if marker in content:
            content = content.split(marker, 1)[1].strip()
            break
    return f"#{idx}\n指令内容: {content}\n待审: {text}"


