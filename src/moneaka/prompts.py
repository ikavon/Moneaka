def judge_batch_item(idx: int, draft: str, text: str) -> str:
    """语义评委的题面。

    ``draft`` 现在是「语气 + 内容」两行指令，但只有**内容行**参与语义比对——
    语气行本来就是写给模型看的指令，把它当内容去比会把「照指令演」误判成「编造」。
    """
    content = draft
    for marker in ("内容:", "内容："):
        if marker in content:
            content = content.split(marker, 1)[1].strip()
            break
    return f"#{idx}\n指令内容: {content}\n待审: {text}"


def judge_voice_item(idx: int, user_msg: str, text: str) -> str:
    """盲评风格：给玩家原话作语境，**不给草稿**。

    为什么不给草稿：一旦给了，评委就把「内容能不能接上」当作「像不像她」，
    于是「照抄草稿 + 加个标签」也拿高分（实测 polish 与草稿逐字相同的 23/60 拿了 3.30）。
    为什么必须给玩家原话：完全不给语境时评委失去标尺，连真实 DAA4 输出都被打到 2.41。
    """
    return f"#{idx}\n玩家说: {user_msg}\n她的回复: {text}"
