def render_context(context: list[dict] | None, user: str | None,
                   last_n: int = 4, clip: int = 60) -> str:
    """把对话历史压成几行短文本。

    情绪标签**是上下文的函数**：对方说「我配不上你」和说「今天下雨」，正确的开头标签
    完全不同。之前没把上下文喂进训练输入，标签只能从「内容」行猜，天然退回
    边际分布的众数（实测 65% 逐位吻合、错例清一色选了「微笑」）。

    只留最近 ``last_n`` 条、每条截 ``clip`` 字：真实 MAICA 上下文很长，
    而润色器是句级后处理，给多了白吃序列长度（本卡 seq 只能给到 ~900）。
    历史里的 ``[情绪标签]`` 一律剥掉：那是我们想学的东西，不能当输入漏给模型。
    """
    from .contract import TAG_RE

    lines: list[str] = []
    for m in (context or [])[-last_n:]:
        who = "莫妮卡" if m.get("role") == "assistant" else "玩家"
        body = TAG_RE.sub("", m.get("content", "")).strip()
        if body:
            lines.append(f"{who}: {body[:clip]}")
    # context 的最后一条往往已经是当前这句 user（corpus 里就是这样切的），
    # 再补一遍会出现重复行——去重要按「内容」而不是按整行，因为 role 前缀不同。
    if user and str(user).strip() and (not lines or not lines[-1].endswith(str(user).strip()[:clip])):
        lines.append(f"玩家: {str(user).strip()[:clip]}")
    return "\n".join(lines[-last_n:]) if lines else "(无历史)"


